const assert = require('node:assert/strict');
global.window = global;
require('../core/gdv-search.js');
require('../core/zip-utils.js');
const core = global.PTISharedCore;
assert.ok(core, 'Shared Core should be initialized');
assert.equal(core.xmlEsc(`<&>"'`), '&lt;&amp;&gt;&quot;&apos;');
assert.equal(core.crc32(new TextEncoder().encode('123456789')), 0xcbf43926);
assert.deepEqual([...core.u16(0x1234)], [0x34, 0x12]);
assert.deepEqual([...core.u32(0x12345678)], [0x78, 0x56, 0x34, 0x12]);
assert.deepEqual([...core.catBytes([new Uint8Array([1,2]), new Uint8Array([3])])], [1,2,3]);
assert.equal(new TextDecoder().decode(core.b64Bytes('SGVsbG8=')), 'Hello');
assert.equal(new TextDecoder().decode(core.dataUrlBytes('data:text/plain;base64,SGVsbG8=')), 'Hello');
const payload = new TextEncoder().encode('Core ZIP round-trip');
const archive = core.zipStore([{name:'sample.txt', data:payload}]);
const files = core.unzipStore(archive);
assert.equal(core.textFile(files, 'sample.txt'), 'Core ZIP round-trip');
console.log('Shared ZIP/XML Core tests passed.');
