const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1200,height:900}});
  await page.goto('http://127.0.0.1:4173/tests/project5-caption-tools-browser.html');
  await page.waitForSelector('#p5SelectionToolbar');
  await page.locator('#p5RowGap').evaluate(el=>{el.value='24';el.dispatchEvent(new Event('input',{bubbles:true}));});
  assert.equal(await page.evaluate(()=>window.__state.rowGap),24,'row gap updates shared Core state');
  assert.equal(await page.locator('#layoutPreview').evaluate(el=>el.style.rowGap),'24px','layout preview reflects row gap');
  await page.locator('#p5ColumnGap').evaluate(el=>{el.value='30';el.dispatchEvent(new Event('input',{bubbles:true}));});
  assert.equal(await page.evaluate(()=>window.__state.columnGap),30,'column gap updates shared Core state');
  assert.equal(await page.locator('#layoutPreview').evaluate(el=>el.style.columnGap),'30px','layout preview reflects column gap');
  assert.ok(await page.evaluate(()=>window.__layoutSaves)>=2,'layout spacing changes schedule draft save');
  const thumbs=()=>page.locator('#grid .thumb');
  await thumbs().nth(0).locator('.imgBox').click();
  assert.equal(await thumbs().nth(0).getAttribute('aria-selected'),'true','plain click selects one image');
  await page.keyboard.down('Control');await thumbs().nth(2).locator('.imgBox').click();await page.keyboard.up('Control');
  assert.equal(await thumbs().nth(0).getAttribute('aria-selected'),'true');
  assert.equal(await thumbs().nth(2).getAttribute('aria-selected'),'true','Ctrl-click adds non-adjacent image');
  await thumbs().nth(3).locator('.imgBox').click({modifiers:['Shift']});
  assert.equal(await thumbs().nth(2).getAttribute('aria-selected'),'true');
  assert.equal(await thumbs().nth(3).getAttribute('aria-selected'),'true','Shift-click selects a range from last anchor');
  await page.locator('#p5BulkCaption').click();
  await page.locator('#p5CaptionInput').fill('  tổn   thất xe. hư hỏng  ');
  assert.equal(await page.locator('#p5CaptionPreview').textContent(),'Tổn thất xe. Hư hỏng');
  await page.locator('#p5CaptionApply').click();
  const captions=await page.evaluate(()=>window.__state.current.items.map(x=>x.caption));
  assert.equal(captions[2],'Tổn thất xe. Hư hỏng');
  assert.equal(captions[3],'Tổn thất xe. Hư hỏng');
  assert.equal(captions[0],'old 1','unselected image caption remains unchanged');
  assert.equal(await page.evaluate(()=>window.__draftSaves),1,'bulk caption schedules exactly one draft save');
  const individual=thumbs().nth(0).locator('textarea');
  await individual.fill('  tổn   thất riêng. kính vỡ  ');
  assert.equal(await individual.inputValue(),'Tổn thất riêng. Kính vỡ ','individual caption auto-corrects silently while typing and preserves trailing space');
  await individual.blur();
  assert.equal(await individual.inputValue(),'Tổn thất riêng. Kính vỡ','individual caption trims on blur');
  assert.equal(await page.evaluate(()=>window.__state.current.items[0].caption),'Tổn thất riêng. Kính vỡ','normalized individual caption is saved to shared Core state');
  assert.equal(await page.evaluate(()=>window.__lastMessage),'Đã áp dụng thuyết minh cho 2 ảnh.','AutoCorrect does not add a notification');
  await page.locator('#p5SelectionMode').click();
  const box0=await thumbs().nth(0).locator('.imgBox').boundingBox();
  const box1=await thumbs().nth(1).locator('.imgBox').boundingBox();
  await page.mouse.move(box0.x+10,box0.y+10);await page.mouse.down();
  await page.mouse.move(box1.x+box1.width-2,box1.y+box1.height-2,{steps:5});await page.mouse.up();
  assert.equal(await thumbs().nth(0).getAttribute('aria-selected'),'true','lasso includes first image');
  assert.equal(await thumbs().nth(1).getAttribute('aria-selected'),'true','lasso includes intersected image');
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  await mobile.goto('http://127.0.0.1:4173/tests/project5-caption-tools-browser.html');
  await mobile.locator('#p5SelectionMode').click();
  await mobile.locator('#grid .thumb').nth(0).locator('.imgBox').tap();
  await mobile.locator('#grid .thumb').nth(1).locator('.imgBox').tap();
  assert.equal(await mobile.locator('#grid .thumb').nth(0).getAttribute('aria-selected'),'true','mobile tap selects first image');
  assert.equal(await mobile.locator('#grid .thumb').nth(1).getAttribute('aria-selected'),'true','mobile tap can select multiple images');
  await mobile.close();
  console.log('PASS: Project 5 selection, lasso, bulk caption and mobile tap browser tests');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
